
"""
SmartStudy AI - Supabase PostgreSQL Database and Authentication
Handles user storage, password hashing, and JWT token management.
"""

import os
import datetime
import logging
from functools import wraps

import psycopg
from psycopg.rows import dict_row
from psycopg.errors import UniqueViolation

from flask import request, jsonify, g
from werkzeug.security import generate_password_hash, check_password_hash
import jwt

logger = logging.getLogger(__name__)

DATABASE_URL = os.getenv("DATABASE_URL")
JWT_SECRET_KEY = os.getenv(
    "JWT_SECRET_KEY",
    "smartstudy-ai-secure-jwt-secret-key-2026"
)
JWT_ALGORITHM = "HS256"


def get_db_connection():
    """Creates a connection to Supabase PostgreSQL."""
    if not DATABASE_URL:
        raise RuntimeError("DATABASE_URL is not configured.")

    return psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row,
        sslmode="require"
    )


def init_db():
    """Initializes the PostgreSQL database."""
    with get_db_connection() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS public.users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                email TEXT UNIQUE NOT NULL,
                password_hash TEXT NOT NULL,
                created_at TIMESTAMPTZ DEFAULT NOW()
            )
        """)

    logger.info("Supabase PostgreSQL database initialized successfully.")


def create_user(name: str, email: str, password: str):
    """Creates a new user with a hashed password."""

    name = name.strip()
    email = email.strip().lower()

    if not name:
        raise ValueError("Full Name is required.")

    if not email or "@" not in email:
        raise ValueError("A valid email address is required.")

    if not password or len(password) < 6:
        raise ValueError("Password must be at least 6 characters long.")

    password_hash = generate_password_hash(
        password,
        method="pbkdf2:sha256"
    )

    try:
        with get_db_connection() as conn:
            row = conn.execute(
                """
                INSERT INTO public.users (name, email, password_hash)
                VALUES (%s, %s, %s)
                RETURNING id
                """,
                (name, email, password_hash)
            ).fetchone()

        return {
            "id": row["id"],
            "name": name,
            "email": email
        }

    except UniqueViolation:
        raise ValueError(
            "An account with this email address already exists. Please log in."
        )


def authenticate_user(email: str, password: str):
    """Authenticates user credentials."""

    email = email.strip().lower()

    with get_db_connection() as conn:
        row = conn.execute(
            """
            SELECT id, name, email, password_hash
            FROM public.users
            WHERE email = %s
            """,
            (email,)
        ).fetchone()

    if not row:
        return None

    if check_password_hash(row["password_hash"], password):
        return {
            "id": row["id"],
            "name": row["name"],
            "email": row["email"]
        }

    return None


def get_user_by_id(user_id: int):
    """Retrieves a user profile by ID."""

    with get_db_connection() as conn:
        row = conn.execute(
            """
            SELECT id, name, email, created_at
            FROM public.users
            WHERE id = %s
            """,
            (user_id,)
        ).fetchone()

    if row:
        return {
            "id": row["id"],
            "name": row["name"],
            "email": row["email"],
            "created_at": str(row["created_at"])
        }

    return None


def generate_token(
    user_id: int,
    email: str,
    name: str,
    remember_me: bool = True
) -> str:

    days = 14 if remember_me else 2

    exp = datetime.datetime.now(
        datetime.timezone.utc
    ) + datetime.timedelta(days=days)

    payload = {
        "sub": str(user_id),
        "user_id": user_id,
        "email": email,
        "name": name,
        "exp": exp
    }

    return jwt.encode(
        payload,
        JWT_SECRET_KEY,
        algorithm=JWT_ALGORITHM
    )


def decode_token(token: str):
    """Validates a JWT token."""

    try:
        return jwt.decode(
            token,
            JWT_SECRET_KEY,
            algorithms=[JWT_ALGORITHM]
        )

    except (jwt.ExpiredSignatureError, jwt.InvalidTokenError) as e:
        logger.warning("Token validation error: %s", e)
        return None


def require_auth(f):
    """Protects routes requiring authentication."""

    @wraps(f)
    def decorated(*args, **kwargs):

        auth_header = request.headers.get("Authorization", "")

        if not auth_header.startswith("Bearer "):
            return jsonify({
                "success": False,
                "error": "Authentication required. Please log in."
            }), 401

        token = auth_header.split(" ", 1)[1].strip()
        payload = decode_token(token)

        if not payload:
            return jsonify({
                "success": False,
                "error": "Session expired or invalid token."
            }), 401

        uid = payload.get("user_id") or payload.get("sub")

        try:
            uid = int(uid)
        except (ValueError, TypeError):
            return jsonify({
                "success": False,
                "error": "Invalid user token identity."
            }), 401

        user = get_user_by_id(uid)

        if not user:
            return jsonify({
                "success": False,
                "error": "User account no longer exists."
            }), 401

        g.current_user = user

        return f(*args, **kwargs)

    return decorated
